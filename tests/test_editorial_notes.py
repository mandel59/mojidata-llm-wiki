class EditorialNotesTests(unittest.TestCase):
    def write_topic(self, bundle, slug, body):
        path = bundle / "topics" / f"{slug}.md"
        path.parent.mkdir(exist_ok=True)
        path.write_text(
            f"---\ntype: Topic\ntitle: {slug}\nslug: {slug}\nstatus: active\n---\n\n{body}", encoding="utf-8"
        )
        return path

    def test_inline_multiline_and_table_notes_preserve_article_text(self):
        source = "A<!-- editorial: 調査 -->B\n| 字 | a<!-- editorial:\n要照合\n-->b |\n"
        result = split_editorial_notes(source, Path("page.md"), first_line=8)
        self.assertEqual(result.article, "AB\n| 字 | ab |\n")
        self.assertEqual([note.text for note in result.notes], ["調査", "要照合"])
        self.assertEqual([(n.line, n.end_line) for n in result.notes], [(8, 8), (9, 11)])
        self.assertEqual(len(result.masked()), len(source))
        self.assertEqual(result.masked().count("\n"), source.count("\n"))
        self.assertEqual(preserve_editorial_notes(source, result.article), source)

    def test_fences_inline_code_ordinary_comments_and_escapes_are_not_notes(self):
        samples = [
            "```markdown\n<!-- editorial: example -->\n```\n",
            "~~~~\n~~~\n<!-- editorial: example -->\n~~~~\n",
            "> ```\n> <!-- editorial: example -->\n> ```\n",
            "- ~~~markdown\n  <!-- editorial: example -->\n  ~~~\n",
            "> - ~~~markdown\n>   <!-- editorial: example -->\n>   ~~~\n",
            "```markdown\r\n<!-- editorial: example -->\r\n```\r\n",
            "``inline ` <!-- editorial: example -->``\n",
            "`multiline\n<!-- editorial: example -->`\n",
            "```inline <!-- editorial: example -->```\n",
            "<!-- ordinary comment: <!-- editorial: example -->\n",
            "\\<!-- editorial: example -->\n",
        ]
        for source in samples:
            with self.subTest(source=source):
                result = split_editorial_notes(source)
                self.assertEqual(result.errors, [])
                self.assertEqual(result.notes, ())
                self.assertEqual(result.article, source)
        self.assertEqual(article_text("` unmatched\n<!-- editorial: actual -->\n"), "` unmatched\n\n")
        self.assertEqual(article_text("```x``` <!-- editorial: actual -->\n"), "```x``` \n")

    def test_other_markers_are_preserved(self):
        source = "<!-- generated by tool -->\n<!-- events:start -->\n<!-- editorial: note -->\n<!-- events:end -->"
        self.assertEqual(article_text(source), source.replace("<!-- editorial: note -->", ""))

    def test_invalid_notes_keep_source_and_fail_article_consumers(self):
        for source in ["before<!-- editorial: unclosed\nafter", "<!-- editorial: a <!-- editorial: b --> -->"]:
            result = split_editorial_notes(source, Path("page.md"))
            self.assertTrue(result.errors)
            self.assertEqual(result.article, source)
            with self.assertRaisesRegex(ValueError, "page.md:1: editorial note"):
                result.masked()
            with self.assertRaises(ValueError):
                article_text(source)

    def test_unchanged_note_only_fragment_is_preserved(self):
        source = "<!-- editorial: only note -->"
        self.assertEqual(preserve_editorial_notes(source, ""), source)

    def test_cli_reports_invalid_note_without_silently_truncating(self):
        with tempfile.TemporaryDirectory() as tmp:
            path = self.write_topic(Path(tmp), "broken", "# Broken\n<!-- editorial: not closed\nimportant text\n")
            output, errors = io.StringIO(), io.StringIO()
            with contextlib.redirect_stdout(output), contextlib.redirect_stderr(errors):
                self.assertEqual(document_sections.main(["read", str(path)]), 1)
            self.assertEqual(output.getvalue(), "")
            self.assertIn("editorial note is not closed", errors.getvalue())
            self.assertIn("important text", path.read_text(encoding="utf-8"))

    def test_read_page_positions_context_and_frontmatter_update(self):
        with tempfile.TemporaryDirectory() as tmp:
            bundle = Path(tmp)
            path = self.write_topic(bundle, "sample", "# Sample\n\n## 経緯\n\n本文。\n<!-- editorial:\n出典を確認。\n-->\n後の本文。\n")
            page = read_page(path, bundle)
            self.assertIn("<!-- editorial:", page.body)
            self.assertNotIn("<!-- editorial:", page.article_body)
            row = document_sections.editorial_note_rows(page)[0]
            self.assertEqual(row["line"], 13)
            self.assertEqual(row["end_line"], 15)
            self.assertEqual(row["heading"], "経緯")
            self.assertIn("本文。", row["context_before"])
            self.assertIn("後の本文。", row["context_after"])
            update_frontmatter(path, lambda data: {**data, "tags": ["review"]}, bundle)
            updated = read_page(path, bundle)
            self.assertEqual(updated.body.lstrip(), page.body.lstrip())
            self.assertEqual(updated.frontmatter["tags"], ["review"])

    def test_graph_and_document_candidates_ignore_note_only_mentions(self):
        with tempfile.TemporaryDirectory() as tmp:
            bundle = Path(tmp)
            self.write_topic(bundle, "first", "# First\n<!-- editorial: [second](second.md) L2/26-001 -->\n")
            self.write_topic(bundle, "second", "# Second\n")
            concepts = load_concepts(bundle)
            self.assertNotIn("second", concepts["first"].links)
            self.assertNotIn("first", concepts["second"].backlinks)
            entry = CatalogEntry("utc", "utc-l2-26-001", "L2/26-001", "2026-01-01", "Test", "UTC", "available", "https://example.com/doc.pdf")
            self.assertEqual(collect_candidates(concepts, {entry.entry_id: entry}), [])

    def test_headings_and_editing_section_do_not_interpret_note_contents(self):
        source = "# Page\n## One\nA\n<!-- editorial:\n## Fake\n-->\nB\n```\n## Code\n```\n## Two\nC\n"
        self.assertEqual([h.title for h in document_sections.detect_headings(source)], ["Page", "One", "Two"])
        section = document_sections.extract_section(source, "One")
        self.assertIn("## Fake", section)
        self.assertIn("B", section)
        self.assertNotIn("## Two", section)

    def test_cli_views_and_cross_page_note_inventory(self):
        with tempfile.TemporaryDirectory() as tmp:
            bundle = Path(tmp)
            path = self.write_topic(bundle, "first", "# First\ntext<!-- editorial: check -->\n")
            self.write_topic(bundle, "second", "# Second\n<!-- editorial: second task -->\n")
            for view in ["article", "editing", "notes"]:
                output = io.StringIO()
                with contextlib.redirect_stdout(output):
                    status = document_sections.main(["read", str(path), "--view", view, "--format", "json"])
                self.assertEqual(status, 0)
                if view == "article":
                    self.assertNotIn("editorial:", output.getvalue())
                elif view == "editing":
                    self.assertIn("<!-- editorial: check -->", output.getvalue())
                else:
                    self.assertEqual(json.loads(output.getvalue())[0]["text"], "check")
            output = io.StringIO()
            with contextlib.redirect_stdout(output):
                self.assertEqual(document_sections.main(["notes", "--bundle", str(bundle), "--format", "json"]), 0)
            self.assertEqual(len(json.loads(output.getvalue())), 2)

    def test_fixers_preserve_notes_and_report_source_lines(self):
        note = "<!-- editorial:\nUTC #999 and `PRI \\#999`\n-->"
        source = "UTC #188\n" + note + "\nUTC #189 and `PRI \\#546`\n"
        fixed, findings = escape_obsidian_tags_in_markdown(source)
        self.assertIn(note, fixed)
        self.assertEqual(findings, [(1, "#188"), (5, "#189")])
        updated, findings = unescape_hashes_in_inline_code_markdown(fixed)
        self.assertIn(note, updated)
        self.assertEqual(findings, [(5, "`PRI \\#546`")])

    def test_okf_validates_note_syntax_and_links_without_interpreting_headings(self):
        with tempfile.TemporaryDirectory() as tmp:
            bundle = Path(tmp)
            (bundle / "index.md").write_text("<!-- editorial: before heading -->\n# Index\n", encoding="utf-8")
            path = self.write_topic(bundle, "first", "# First\n<!-- editorial: [missing](missing.md) -->\n")
            errors = validate_bundle(bundle, DEFAULT_SCHEMA)
            self.assertTrue(any("broken markdown link" in error for error in errors))
            self.assertFalse(any("should start with a heading" in error for error in errors))
            path.write_text(path.read_text(encoding="utf-8").replace(" -->", ""), encoding="utf-8")
            self.assertTrue(any("editorial note is not closed" in error for error in validate_bundle(bundle, DEFAULT_SCHEMA)))

    def test_stale_claims_and_review_warnings_ignore_notes(self):
        with tempfile.TemporaryDirectory() as tmp:
            bundle = Path(tmp)
            path = self.write_topic(bundle, "first", "# First\n<!-- editorial: IRG N2933 は未確認。まだ event 化していない。 -->\n")
            entry = check_wiki_review.CatalogEntry("irg", "irg-n2933", "IRG N2933", "available", "https://example.com/doc.pdf")
            with patch.object(check_wiki_review, "WIKI", bundle), patch.object(check_wiki_review, "read_page", lambda path: read_page(path, bundle)):
                self.assertEqual(check_wiki_review.check_stale_unavailable_text({entry.entry_id: entry}), [])
                self.assertEqual(check_wiki_review.editorial_body_warnings(), [])
                path.write_text(path.read_text(encoding="utf-8") + "まだ event 化していない。\n", encoding="utf-8")
                self.assertEqual(len(check_wiki_review.editorial_body_warnings()), 1)

    def test_marker_update_retains_notes_and_ignores_note_only_markers(self):
        start, end = "<!-- events:start -->", "<!-- events:end -->"
        note = "<!-- editorial: keep -->"
        source = note + "\n" + start + "\nrow" + note + "\n" + end + "\nTail\n"
        replacement = start + "\nrow\nnew\n" + end
        updated, changed = replace_marker_block(source, start, end, replacement)
        self.assertTrue(changed)
        self.assertEqual(updated.count(note), 2)
        self.assertIn("row" + note, updated)
        # The literal marker strings here are text in a note, not nested HTML.
        hidden = "<!-- editorial: events:start / events:end -->"
        self.assertEqual(replace_marker_block(hidden, "events:start", "events:end", "new"), (hidden, False))

    def test_article_edit_refuses_destroyed_note_anchor(self):
        source = "AAA<!-- editorial: keep -->AAA"
        with self.assertRaisesRegex(ValueError, "removes its context"):
            preserve_editorial_notes(source, "ZZZZZZ")

    def test_document_index_regeneration_preserves_notes(self):
        with tempfile.TemporaryDirectory() as tmp:
            bundle = Path(tmp)
            docs = bundle / "documents"
            docs.mkdir()
            doc = docs / "utc-l2-26-001.md"
            doc.write_text("---\ntype: Source Document\ntitle: Test\nentry_id: utc-l2-26-001\nregistry: utc\ndoc_number: L2/26-001\ndate: 2026-01-01\n---\n# Test\n", encoding="utf-8")
            index = docs / "index.md"
            note = "<!-- editorial: index task -->"
            index.write_text(render_index(bundle).replace("## UTC", note + "\n## UTC"), encoding="utf-8")
            with contextlib.redirect_stdout(io.StringIO()):
                self.assertEqual(generate_document_index(["--bundle", str(bundle)]), 0)
                self.assertEqual(generate_document_index(["--bundle", str(bundle), "--check"]), 0)
            self.assertIn(note + "\n## UTC", index.read_text(encoding="utf-8"))

    def test_event_index_regeneration_preserves_notes(self):
        with tempfile.TemporaryDirectory() as tmp:
            events = Path(tmp)
            note = "<!-- editorial: index task -->"
            (events / "index.md").write_text("# Events\n" + note + "\n", encoding="utf-8")
            with patch.object(generate_event_indexes, "EVENTS", events), patch.object(generate_event_indexes, "render_index", return_value="# Events\n\n"), contextlib.redirect_stdout(io.StringIO()):
                self.assertEqual(generate_event_indexes.main([]), 0)
            self.assertIn(note, (events / "index.md").read_text(encoding="utf-8"))

    def test_timeline_linker_does_not_rewrite_notes(self):
        target = Path("C:/repo/wiki/documents/utc-l2-26-099.md")
        concept = Concept("doc", [], "Source Document", "L2/26-099", target, "documents/doc.md", {}, "", {}, {}, [], [])
        note = "<!-- editorial:\n## Other\n| later | `L2/26-099` |\n-->"
        source = "## 経緯\n" + note + "\n| now | `L2/26-099` |\n"
        updated, count = link_timeline(source, Path("C:/repo/wiki/topics/test.md"), {"l2/26-099": concept})
        self.assertEqual(count, 1)
        self.assertIn(note, updated)
        self.assertIn("[L2/26-099](../documents/utc-l2-26-099.md)", updated)


